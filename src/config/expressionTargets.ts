export type ExpressionBand = 'preschool' | 'school';

export interface ExpressionTask {
  id: string;
  /** 伙伴对孩子念的题干，照念，不加话 */
  ask: string;
  /** 孩子卡住时给的提示句 */
  hint: string;
  /** 判定提示项：人工勾选，不做自动计分 */
  checks: string[];
}

export interface ExpressionFamilyGuide {
  /** 练什么 */
  what: string;
  /** 准备什么 */
  prepare: string;
  /** 怎么开始（照念的那一句） */
  start: string;
  /** 等几秒 */
  wait: string;
  /** 提示顺序 */
  prompts: string;
  /** 算成功的标准 */
  success: string;
  /** 做不到怎么降级 */
  fallback: string;
  /** 时长与频次 */
  dose: string;
  /** 这三件先别做 */
  avoid: string;
}

export interface ExpressionTarget {
  id: string;
  name: string;
  band: ExpressionBand;
  /** 五领域归类，用于统计 */
  domain: '语言沟通' | '语言表达';
  /** 一句话说清练什么，给孩子和家长看 */
  summary: string;
  /** 2 分标准（原文口径） */
  standard2: string;
  /** 常见 1 分情形 */
  onePenalty: string;
  /** 伙伴开场白 */
  opener: string;
  tasks: ExpressionTask[];
  familyGuide: ExpressionFamilyGuide;
}

